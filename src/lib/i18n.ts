export type TranslationKey = keyof typeof en;

/**
 * The strings each language has in hand. English is the fallback and ships with every page; the
 * Chinese strings are their own file, loaded only by a reader who has chosen Chinese.
 */
const dictionaries: Partial<Record<Locale, Record<TranslationKey, string>>> = { en };

/** Whether `t` can speak this language yet; until it can, it answers in English. */
export function isLocaleLoaded(locale: Locale): boolean {
  return dictionaries[locale] !== undefined;
}

/** Fetches a language's strings, once. It never rejects: offline, the page stays in English. */
export async function loadLocale(locale: Locale): Promise<void> {
  if (dictionaries[locale]) return;
  try {
    if (locale === "zh-CN") dictionaries["zh-CN"] = (await import("./i18n-zh.ts")).zhCN;
  } catch {
    // Offline before the file was ever fetched.
  }
}

export function t(
  locale: Locale,
  key: TranslationKey,
  params?: Record<string, string | number>,
): string {
  const template = dictionaries[locale]?.[key] ?? en[key];
  if (!params) return template;

  return Object.entries(params).reduce(
    (text, [paramName, paramValue]) =>
      text.replaceAll(`{${paramName}}`, String(paramValue)),
    template,
  );
}

/** Locale tag to use with `Intl.DateTimeFormat` and similar APIs. */
export function intlLocale(locale: Locale): string {
  return locale === "zh-CN" ? "zh-CN" : "en-US";
}

export function isLocale(value: unknown): value is Locale {
  return value === "en" || value === "zh-CN";
}

export function restoreLocale(storage: Storage): Locale {
  const stored = storage.getItem(LOCALE_STORAGE_KEY);
  return isLocale(stored) ? stored : DEFAULT_LOCALE;
}

export function saveLocale(storage: Storage, locale: Locale) {
  storage.setItem(LOCALE_STORAGE_KEY, locale);
}
